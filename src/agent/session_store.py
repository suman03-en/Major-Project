"""
Session Store
=============
Stores per-user conversation state so the agent can maintain context across
multiple API calls within a single session (e.g. navigating procedure steps,
remembering company type, holding last retrieved chunks).

The default implementation is in-memory (suitable for single-container
deployments).  Swap it for a Redis-backed implementation in production by
implementing the same :class:`SessionStore` protocol.

Usage::

    from src.agent.session_store import InMemorySessionStore

    store = InMemorySessionStore()
    session = store.get_or_create("my-session-id")
    session.active_process = "कम्पनी दर्ता"
    session.current_step = 2
    store.save(session)
"""

from __future__ import annotations

import uuid
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any, Protocol

from src.agent.intent_classifier import IntentType

# ---------------------------------------------------------------------------
# Session state dataclass
# ---------------------------------------------------------------------------

@dataclass
class SessionState:
    """
    Mutable state for a single user conversation session.

    Attributes
    ----------
    session_id:
        Unique identifier (UUID string) generated by the client.
    intent_history:
        Ordered list of the last N classified intents (newest last).
    active_process:
        Name of the Neo4j ``Process`` node the user is currently walking
        through (``None`` if no procedure is active).
    current_step:
        1-based index of the step the user is *currently on*.
        ``0`` means the process has not started yet.
    total_steps:
        Total steps in the active process (cached to avoid repeated Neo4j
        queries).
    confirmed_answers:
        Slot-fills collected during the session, e.g.
        ``{"company_type": "private", "share_capital": "10 lakh"}``.
    last_chunks:
        The most recently retrieved RAG chunks, used for follow-up
        questions that reference "it" / "त्यो" / "उक्त".
    created_at / updated_at:
        Timestamps (UTC) for TTL eviction and audit.
    """

    session_id: str
    intent_history: list[IntentType] = field(default_factory=list)
    active_process: str | None = None
    current_step: int = 0
    total_steps: int = 0
    confirmed_answers: dict[str, str] = field(default_factory=dict)
    last_chunks: list[dict[str, Any]] = field(default_factory=list)
    created_at: datetime = field(default_factory=lambda: datetime.now(tz=timezone.utc))
    updated_at: datetime = field(default_factory=lambda: datetime.now(tz=timezone.utc))

    # Maximum entries kept in intent_history
    _MAX_HISTORY: int = field(default=20, init=False, repr=False, compare=False)

    def push_intent(self, intent: IntentType) -> None:
        """Append *intent* to history, keeping at most ``_MAX_HISTORY`` items."""
        self.intent_history.append(intent)
        if len(self.intent_history) > self._MAX_HISTORY:
            self.intent_history = self.intent_history[-self._MAX_HISTORY :]
        self.updated_at = datetime.now(tz=timezone.utc)

    @property
    def has_active_process(self) -> bool:
        """``True`` when the user is mid-procedure."""
        return self.active_process is not None

    @property
    def procedure_complete(self) -> bool:
        """``True`` when all steps have been walked through."""
        return (
            self.has_active_process
            and self.total_steps > 0
            and self.current_step > self.total_steps
        )


# ---------------------------------------------------------------------------
# Protocol (allows swapping in Redis or any other backend)
# ---------------------------------------------------------------------------

class SessionStore(Protocol):
    """Interface that every session store backend must satisfy."""

    def get_or_create(self, session_id: str) -> SessionState:
        """Return the existing session or create a new one."""
        ...

    def save(self, session: SessionState) -> None:
        """Persist the updated session state."""
        ...

    def delete(self, session_id: str) -> None:
        """Remove a session (logout / expiry)."""
        ...


# ---------------------------------------------------------------------------
# In-memory implementation
# ---------------------------------------------------------------------------

class InMemorySessionStore:
    r"""
    Thread-safe\* in-memory session store.

    \* The GIL makes dict operations atomic in CPython; for true
    multi-threaded safety use a ``threading.Lock`` or move to Redis.

    Parameters
    ----------
    max_sessions : int
        Maximum number of concurrent sessions to keep.  Oldest session is
        evicted when this limit is reached.
    """

    def __init__(self, max_sessions: int = 1000) -> None:
        self._store: dict[str, SessionState] = {}
        self._max = max_sessions

    def get_or_create(self, session_id: str = "") -> SessionState:
        """
        Return the session for *session_id*, or create a new one.

        If *session_id* is empty a fresh UUID is generated automatically.
        """
        if not session_id:
            session_id = str(uuid.uuid4())

        if session_id not in self._store:
            if len(self._store) >= self._max:
                # Evict the oldest session by creation time
                oldest = min(self._store.values(), key=lambda s: s.created_at)
                del self._store[oldest.session_id]

            self._store[session_id] = SessionState(session_id=session_id)

        return self._store[session_id]

    def save(self, session: SessionState) -> None:
        """Upsert *session* into the store."""
        session.updated_at = datetime.now(tz=timezone.utc)
        self._store[session.session_id] = session

    def delete(self, session_id: str) -> None:
        """Remove *session_id* if it exists."""
        self._store.pop(session_id, None)

    def __len__(self) -> int:
        return len(self._store)
